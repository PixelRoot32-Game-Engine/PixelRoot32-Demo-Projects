#!/usr/bin/env python3
"""Pack the ASCII art in art_source.py into the 4bpp headers the engine draws.

    python generate_assets.py [path/to/midway_clone]
    python generate_assets.py --check     # verify only, write nothing
    python generate_assets.py --preview   # print the art back as ASCII

Nothing here is compiled or shipped, and nothing here is versioned -
docs/audits/ is gitignored. This stands in for the PixelRoot32 Tilemap Editor
and Sprite Compiler: it takes an authoring format a human can edit and emits
the same C++ those tools emit, into the demo's src/assets/. That is
the same split legend_of_clone and metroidvania have; the output is what the
repository carries and what reviewers read.

Why a tool rather than hand-written headers:

The engine's 4bpp format packs two pixels per byte with the LOW nibble holding
the LEFT pixel (Renderer.cpp:605-606), and sprite rows are declared as
uint16_t. On a little-endian target that means the hex digits of a literal run
in the opposite order to the pixels they draw: 0x2220 is the pixel run 0,2,2,2.
Hand-authoring that is not difficult, it is merely impossible to do reliably -
every mirrored sprite is one transposed nibble away from a bug that looks like
an art mistake.
"""

