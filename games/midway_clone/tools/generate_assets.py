def build_tileset(bg_palette):
    packed_tiles = []
    for name, is_land, doc, rows in art.TILES:
        packed = pack_rows(rows, bg_palette, art.TILE_SIZE, art.TILE_SIZE, name)
        verify(rows, packed, bg_palette, art.TILE_SIZE, art.TILE_SIZE, name)
        packed_tiles.append((name, is_land, doc, rows, packed))
    return packed_tiles


def emit_tilemap_header(packed_tiles):
    guard = f"{GUARD_PREFIX}_OCEAN_TILEMAP_H"
    bytes_per_tile = art.TILE_SIZE * art.TILE_SIZE // 2

    out = [BANNER, f"#ifndef {guard}", f"#define {guard}", "",
           '#include "platforms/PlatformDefaults.h"', "",
           "#ifdef PIXELROOT32_ENABLE_4BPP_SPRITES", "",
           '#include "graphics/Renderer.h"', "#include <stdint.h>", "",
           "/**",
           " * @file OceanTileMap.h",
           f" * @brief The stage: {LEVEL_WIDTH}x{LEVEL_HEIGHT} tiles of ocean, islands and one carrier.",
           " *",
           f" * Tiles are {art.TILE_SIZE}x{art.TILE_SIZE}, the same size legend_of_clone and metroidvania use.",
           " * The NES original is an 8x8 machine and this map was 8x8 first, which drew a",
           " * better coastline; it was doubled for frame rate. The renderer pays a per-tile",
           " * cost that does not shrink with the tile, so a 240x240 screen costs 900 blits",
           " * at 8px and 225 at 16px for the identical 57,600 pixels.",
           " *",
           " * Row 0 is the NORTH end of the stage. The camera starts at the bottom and",
           " * climbs, so the player meets the highest row numbers first.",
           " */", "",
           f"namespace {NAMESPACE} {{", "namespace ocean {", "",
           "    // --- Dimensions ---",
           f"    static const uint8_t  TILE_SIZE  = {art.TILE_SIZE};",
           f"    static const uint8_t  MAP_WIDTH  = {LEVEL_WIDTH};",
           f"    static const uint8_t  MAP_HEIGHT = {LEVEL_HEIGHT};",
           f"    static const uint16_t TILE_COUNT = {len(packed_tiles)};",
           "",
           "    // --- Tile ids ---",
           "    // 1-based: drawTileMap skips index 0, so slot 0 is reserved and never drawn.",
           ""]

    for index, (name, _is_land, doc, _rows, _packed) in enumerate(packed_tiles):
        out.append("    /**")
        out.append(wrap_doc(doc))
        out.append("     */")
        out.append(f"    static const uint8_t TILE_{name} = {index};")
        out.append("")

    out += ["    /**",
            "     * @brief Whether a tile is land, indexed by tile id.",
            "     *",
            "     * Nothing in this game collides with terrain - an aircraft overflies the",
            "     * whole map, which is why there is no TILE_SOLID table here the way",
            "     * legend_of_clone has one. This marks where ground targets can stand.",
            "     */",
            f"    extern const bool TILE_IS_LAND[TILE_COUNT];",
            "",
            "    /** The drawable layer. Valid only after init(). */",
            "    extern pixelroot32::graphics::TileMap4bpp sea;",
            "",
            "    /**",
            "     * @brief Wires the descriptors above to the exported data.",
            "     *",
            "     * Idempotent, and cheap: it assigns pointers, it does not copy pixels.",
            "     * Call once before drawing.",
            "     */",
            "    void init();",
            "",
            "} // namespace ocean",
            f"}} // namespace {NAMESPACE}",
            "",
            "#endif // PIXELROOT32_ENABLE_4BPP_SPRITES",
            "",
            f"#endif // {guard}",
            ""]
    return "\n".join(out), bytes_per_tile


def emit_tilemap_source(packed_tiles, bytes_per_tile, grid):
    out = [BANNER,
           '#include "assets/OceanTileMap.h"', "",
           "#ifdef PIXELROOT32_ENABLE_4BPP_SPRITES", "",
           '#include "assets/TilemapPalette.h"',
           '#include "platforms/PlatformMemory.h"', "",
           f"namespace {NAMESPACE} {{", "namespace ocean {", "",
           "    // --- Tileset pixel data (4bpp) ---",
           "    // Two pixels per byte; the low nibble is the LEFT pixel of the pair.",
           f"    // {len(packed_tiles)} tiles x {bytes_per_tile} bytes.",
           "    static const uint8_t PIXELROOT32_SCENE_FLASH_ATTR TILESET_DATA_POOL[] = {"]

    for name, _is_land, _doc, _rows, packed in packed_tiles:
        out.append(f"        // TILE_{name}")
        out += emit_byte_pool(packed, art.TILE_SIZE // 2)
    out.append("    };")
    out.append("")

    out.append("    static const pixelroot32::graphics::Sprite4bpp PIXELROOT32_SCENE_FLASH_ATTR TILESET_SPRITES[] = {")
    for index, (name, _is_land, _doc, _rows, _packed) in enumerate(packed_tiles):
        offset = index * bytes_per_tile
        out.append(f"        {{ &TILESET_DATA_POOL[{offset}], TILEMAP_PALETTE_MAPPING, "
                   f"TILE_SIZE, TILE_SIZE, 16 }}, // TILE_{name}")
    out.append("    };")
    out.append("")

    out.append("    const bool TILE_IS_LAND[TILE_COUNT] = {")
    for name, is_land, _doc, _rows, _packed in packed_tiles:
        out.append(f"        {'true ' if is_land else 'false'}, // TILE_{name}")
    out.append("    };")
    out.append("")

    glyph = {index: name[0] for index, (name, _a, _b, _c, _d) in enumerate(packed_tiles)}
    glyph[0] = " "
    out.append("    // --- Map indices ---")
    out.append("    // The trailing comment renders each row: O ocean, o whitecap, F foam,")
    out.append("    // S sand, G grass, R rock, D carrier deck.")
    out.append("    static const uint8_t PIXELROOT32_SCENE_FLASH_ATTR SEA_INDICES[] = {")
    letters = {}
    for index, (name, _a, _b, _c, _d) in enumerate(packed_tiles):
        letters[index] = {
            "EMPTY": " ", "OCEAN": "O", "OCEAN_WAVE": "o", "FOAM": "F",
            "SAND": "S", "GRASS": "G", "ROCK": "R", "DECK": "D",
        }.get(name, name[0])
    for y, row in enumerate(grid):
        cells = ", ".join(f"{v}" for v in row)
        picture = "".join(letters[v] for v in row)
        out.append(f"        {cells}, // {y:3d} {picture}")
    out.append("    };")
    out.append("")

    out += ["    pixelroot32::graphics::TileMap4bpp sea;",
            "",
            "    void init() {",
            "        sea.width      = MAP_WIDTH;",
            "        sea.height     = MAP_HEIGHT;",
            "        sea.tileWidth  = TILE_SIZE;",
            "        sea.tileHeight = TILE_SIZE;",
            "        sea.indices    = (uint8_t*)SEA_INDICES;",
            "        sea.tiles      = TILESET_SPRITES;",
            "        sea.tileCount  = TILE_COUNT;",
            "    }",
            "",
            "} // namespace ocean",
            f"}} // namespace {NAMESPACE}",
            "",
            "#endif // PIXELROOT32_ENABLE_4BPP_SPRITES",
            ""]
    return "\n".join(out)


def emit_sprite_header(filename, doc, groups, palette, mapping_include, mapping_name):
    guard = f"{GUARD_PREFIX}_{filename.upper().replace('.', '_')}"
    out = [BANNER, f"#ifndef {guard}", f"#define {guard}", "",
           '#include "platforms/PlatformDefaults.h"', "",
           "#ifdef PIXELROOT32_ENABLE_4BPP_SPRITES", "",
           '#include "graphics/Renderer.h"',
           f'#include "assets/{mapping_include}"',
           "#include <stdint.h>", "",
           doc, "",
           f"namespace {NAMESPACE} {{", ""]

    for group in groups:
        size = group["size"]
        out.append(f"    static const uint8_t {group['prefix']}_WIDTH  = {size};")
        out.append(f"    static const uint8_t {group['prefix']}_HEIGHT = {size};")
        out.append("")

        for name, frame_doc, rows in group["frames"]:
            packed = pack_rows(rows, palette, size, size, name)
            verify(rows, packed, palette, size, size, name)
            out.append("    /**")
            out.append(wrap_doc(frame_doc))
            out.append("     */")
            out.append(f"    static const uint16_t {name}_4BPP[] = {{")
            out += emit_u16_rows(packed, size, size)
            out.append("    };")
            out.append("")

        out.append("    /**")
        out.append(f"     * @brief {group['prefix']} frames as engine sprite descriptors.")
        out.append("     *")
        out.append(f"     * Index with {group['prefix']}Frame below rather than by number.")
        out.append("     */")
        out.append(f"    static const pixelroot32::graphics::Sprite4bpp {group['prefix']}_FRAMES[] = {{")
        for name, _doc, _rows in group["frames"]:
            out.append(f"        {{ reinterpret_cast<const uint8_t*>({name}_4BPP), {mapping_name}, "
                       f"{group['prefix']}_WIDTH, {group['prefix']}_HEIGHT, 16 }},")
        out.append("    };")
        out.append("")
        out.append(f"    enum {group['prefix']}Frame : uint8_t {{")
        for index, (name, _doc, _rows) in enumerate(group["frames"]):
            out.append(f"        {name} = {index},")
        out.append("    };")
        out.append("")
        out.append("    /**")
        out.append(f"     * @brief Frames in {group['prefix']}_FRAMES.")
        out.append("     *")
        out.append("     * Exported rather than left for callers to count, because the callers that")
        out.append("     * need it are animation loops deciding when a sequence has ended - and a")
        out.append("     * hand-written count is the kind that survives one frame being added.")
        out.append("     */")
        out.append(f"    static const uint8_t {group['prefix']}_FRAME_COUNT = {len(group['frames'])};")
        out.append("")

    out.append(f"}} // namespace {NAMESPACE}")
    out.append("")
    out.append("#endif // PIXELROOT32_ENABLE_4BPP_SPRITES")
    out.append("")
    out.append(f"#endif // {guard}")
    out.append("")
    return "\n".join(out)


