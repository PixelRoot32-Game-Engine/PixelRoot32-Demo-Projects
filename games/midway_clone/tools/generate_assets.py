# graphics/Color.h:58-75 - the blitter resolves sprite.palette[value] as one of
# these, then indexes the RGB565 table by the slot's numeric value.
COLOR_SLOTS = [
    "Black", "White", "Navy", "Blue",
    "Cyan", "DarkGreen", "Green", "LightGreen",
    "Yellow", "Orange", "LightRed", "Red",
    "DarkRed", "Purple", "Magenta", "Gray",
]

# Conventional value for every slot, applied before the art palette overrides
# it. Slots the art never touches keep these, so Color::Red still renders red
# for the debug overlay and for error text.
DEFAULT_SLOT_HEX = {
    "Black": "#000000", "White": "#FCFCFC", "Navy": "#0000A8", "Blue": "#0058F8",
    "Cyan": "#3CBCFC", "DarkGreen": "#007800", "Green": "#00A800", "LightGreen": "#B8F818",
    "Yellow": "#F8D878", "Orange": "#E45C10", "LightRed": "#F87858", "Red": "#F80000",
    "DarkRed": "#A81000", "Purple": "#6844FC", "Magenta": "#F878F8", "Gray": "#BCBCBC",
}

NAMESPACE = "midway_clone"
GUARD_PREFIX = "MIDWAY"

BANNER = """// Generated by the midway_clone asset exporter - DO NOT EDIT BY HAND.
//
// The exporter and its ASCII art source are not versioned; see this example's
// README for what they are and where they live. Edit the art there and
// re-export - hand edits here are lost on the next run.
//
// Engine: PixelRoot32
// Mode: 4bpp
"""


# --------------------------------------------------------------------------
# Color
# --------------------------------------------------------------------------

def hex_to_rgb565(hex_str):
    """#RRGGBB -> RGB565, the layout the driver's palette LUT expects."""
    value = hex_str.lstrip("#")
    r, g, b = int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16)
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


class Palette:
    """One 16-slot palette plus the symbol -> 4bpp pixel value assignment.

    Pixel value 0 is the transparent hole and is never looked up, which is why
    the first art symbol lands at value 1 and not at 0.
    """

    def __init__(self, name, spec):
        self.name = name
        self.symbols = {".": 0}
        self.slot_of_value = {}
        self.notes = {}

        for index, (symbol, (slot, hex_str, description)) in enumerate(spec.items(), start=1):
            if symbol == ".":
                raise ValueError("'.' is reserved for the transparent hole")
            if slot not in COLOR_SLOTS:
                raise ValueError(f"{name}: '{symbol}' names unknown Color slot {slot!r}")
            self.symbols[symbol] = index
            self.slot_of_value[index] = slot
            self.notes[index] = (symbol, hex_str, description)

        if len(self.symbols) > 16:
            raise ValueError(f"{name}: {len(self.symbols)} symbols, 4bpp holds 16")

        self.slot_hex = dict(DEFAULT_SLOT_HEX)
        for _, (slot, hex_str, _desc) in spec.items():
            self.slot_hex[slot] = hex_str

    def value(self, symbol):
        if symbol not in self.symbols:
            raise ValueError(f"{self.name}: art uses undeclared symbol {symbol!r}")
        return self.symbols[symbol]

    def symbol_of_value(self, value):
        for symbol, packed in self.symbols.items():
            if packed == value:
                return symbol
        raise ValueError(f"{self.name}: no symbol for pixel value {value}")


# --------------------------------------------------------------------------
# 4bpp packing
# --------------------------------------------------------------------------

def pack_rows(rows, palette, expect_w, expect_h, label):
    """ASCII grid -> packed 4bpp bytes, low nibble first.

    Validates shape before packing. A grid that is one character short would
    otherwise pack into a sprite that renders with a diagonal shear, which is
    a confusing thing to debug from a screenshot.
    """
    if len(rows) != expect_h:
        raise ValueError(f"{label}: {len(rows)} rows, expected {expect_h}")
    if expect_w % 2 != 0:
        raise ValueError(f"{label}: width {expect_w} is odd; 4bpp packs pixel pairs")

    packed = bytearray()
    for y, row in enumerate(rows):
        if len(row) != expect_w:
            raise ValueError(f"{label}: row {y} is {len(row)} chars, expected {expect_w}")
        for x in range(0, expect_w, 2):
            left = palette.value(row[x])
            right = palette.value(row[x + 1])
            packed.append((left & 0x0F) | ((right & 0x0F) << 4))
    return bytes(packed)


def unpack_rows(packed, palette, width, height):
    """Inverse of pack_rows, used to prove the round trip."""
    rows = []
    stride = width // 2
    for y in range(height):
        row = []
        for x in range(stride):
            byte = packed[y * stride + x]
            row.append(palette.symbol_of_value(byte & 0x0F))
            row.append(palette.symbol_of_value((byte >> 4) & 0x0F))
        rows.append("".join(row))
    return rows


def verify(rows, packed, palette, width, height, label):
    restored = unpack_rows(packed, palette, width, height)
    if restored != list(rows):
        for y, (want, got) in enumerate(zip(rows, restored)):
            if want != got:
                raise AssertionError(
                    f"{label}: round trip differs at row {y}\n"
                    f"  source: {want}\n"
                    f"  packed: {got}"
                )
        raise AssertionError(f"{label}: round trip differs in row count")


