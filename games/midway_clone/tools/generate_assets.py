class Lcg:
    """Deterministic 32-bit LCG (Numerical Recipes constants).

    A seeded generator rather than a hand-drawn map: the sea is 200 rows of
    mostly-identical water, and hand-placing six thousand tiles to get a
    scattering of whitecaps is data entry, not level design. The islands and
    the carrier ARE hand-placed, below - those are the parts a player reads.
    """

    def __init__(self, seed):
        self.state = seed & 0xFFFFFFFF

    def next(self):
        self.state = (1664525 * self.state + 1013904223) & 0xFFFFFFFF
        return self.state

    def chance(self, one_in):
        return (self.next() >> 16) % one_in == 0


# 15x100 tiles at 16 px is 240x1600 px - the SAME world the 30x200 8px map
# described. That is deliberate: kCameraStartY, the stage length and every
# trigger in the wave table are in world pixels, so halving the grid while
# doubling the tile leaves all of them untouched.
LEVEL_WIDTH = 15
LEVEL_HEIGHT = 100

# (center row, center col, half-width, half-height, has_rock_core)
# Row 0 is the NORTH end of the stage. The camera starts at the bottom and
# climbs, so these are listed in the order the player meets them: last first.
#
# Halved from the 8px grid, radii included, so every island covers the same
# pixels it did before. Radii are small integers now, which costs some
# roundness - an island is a 5-tile blob rather than a 10-tile ellipse. That
# coarseness is the price of the tile size, and it shows up here rather than in
# the art.
ISLANDS = [
    (88, 3, 2, 2, False),
    (76, 11, 3, 2, True),
    (64, 6, 2, 2, False),
    (52, 12, 2, 3, True),
    (40, 3, 3, 2, True),
    (28, 8, 3, 2, True),
    (16, 4, 2, 2, False),
]

# The carrier that closes the stage: a deck plate the player crosses head-on.
# Three tiles wide by eight tall is 48x128 px - long enough that the deck fills
# half the screen's height while the player is over it.
CARRIER = (5, 12, 6, 8)  # (row_start, row_end, col_start, col_end) inclusive


def build_level(tile_id):
    ocean = tile_id["OCEAN"]
    wave = tile_id["OCEAN_WAVE"]
    foam = tile_id["FOAM"]
    sand = tile_id["SAND"]
    grass = tile_id["GRASS"]
    rock = tile_id["ROCK"]
    deck = tile_id["DECK"]

    grid = [[ocean] * LEVEL_WIDTH for _ in range(LEVEL_HEIGHT)]

    rng = Lcg(0x31393433)  # "1943"
    for y in range(LEVEL_HEIGHT):
        for x in range(LEVEL_WIDTH):
            if rng.chance(7):
                grid[y][x] = wave

    def ellipse(cy, cx, rx, ry, limit):
        cells = []
        for y in range(max(0, cy - ry - 2), min(LEVEL_HEIGHT, cy + ry + 3)):
            for x in range(max(0, cx - rx - 2), min(LEVEL_WIDTH, cx + rx + 3)):
                dx = (x - cx) / float(rx)
                dy = (y - cy) / float(ry)
                if dx * dx + dy * dy <= limit:
                    cells.append((y, x))
        return cells

    for cy, cx, rx, ry, has_rock in ISLANDS:
        for y, x in ellipse(cy, cx, rx, ry, 1.9):
            grid[y][x] = foam
        for y, x in ellipse(cy, cx, rx, ry, 1.0):
            grid[y][x] = sand
        for y, x in ellipse(cy, cx, rx, ry, 0.55):
            grid[y][x] = grass
        if has_rock:
            for y, x in ellipse(cy, cx, rx, ry, 0.18):
                grid[y][x] = rock

    r0, r1, c0, c1 = CARRIER
    # An inverted rectangle makes both range() calls below empty, which places
    # no deck at all and reports success. Ask loudly instead.
    if r1 < r0 or c1 < c0:
        raise ValueError(f"CARRIER rectangle is inverted: rows {r0}..{r1}, cols {c0}..{c1}")
    for cy, cx, rx, ry, _has_rock in ISLANDS:
        if not (0 <= cy < LEVEL_HEIGHT and 0 <= cx < LEVEL_WIDTH):
            raise ValueError(f"island centred at ({cy}, {cx}) falls outside the map")

    for y in range(max(0, r0 - 1), min(LEVEL_HEIGHT, r1 + 2)):
        for x in range(max(0, c0 - 1), min(LEVEL_WIDTH, c1 + 2)):
            grid[y][x] = foam
    for y in range(r0, r1 + 1):
        for x in range(c0, c1 + 1):
            grid[y][x] = deck

    return grid


