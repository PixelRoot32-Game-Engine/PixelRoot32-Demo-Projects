# --------------------------------------------------------------------------

# Two ASCII cells per pixel, so a 16px sprite prints at roughly its real aspect
# ratio in a terminal. ASCII rather than block-drawing characters because the
# Windows console this is most often run on encodes cp1252 and would raise on
# anything outside it - a preview that crashes is worse than a coarse one.
PREVIEW_INK = {
    ".": "  ", "k": "##", "n": "::", "b": "..", "c": "~~", "d": "vv",
    "g": "VV", "a": "--", "o": "oo", "r": "rr", "y": "==", "w": "@@",
    "s": "++", "h": "**", "f": "ff", "e": ",,",
}


def preview(rows, title):
    print(f"\n  {title}")
    for row in rows:
        print("    " + "".join(PREVIEW_INK.get(ch, "??") for ch in row))


# --------------------------------------------------------------------------
# Main
# --------------------------------------------------------------------------

def locate_example():
    """Return the demo root - the directory holding src/.

    This script used to live under the engine's gitignored
    docs/audits/_dev_tools/, outside the tree it writes to, and walked up
    looking for examples/midway_clone. It now sits inside the demo itself, so
    the answer is the parent of this tools/ directory.
    """
    here = os.path.dirname(os.path.abspath(__file__))
    candidate = os.path.dirname(here)
    if os.path.isdir(os.path.join(candidate, "src")):
        return candidate
    raise SystemExit(
        candidate + " does not look like the midway_clone demo (no src/ under "
        "it). This script expects to live in <demo>/tools/. Pass the demo path "
        "explicitly:\n    python generate_assets.py path/to/midway_clone")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("example", nargs="?", default=None,
                        help="path to the midway_clone demo; found automatically if omitted")
    parser.add_argument("--check", action="store_true", help="validate only, write nothing")
    parser.add_argument("--preview", action="store_true", help="print the art back as ASCII")
    args = parser.parse_args()

    example = args.example or locate_example()
    out_dir = os.path.join(example, "src", "assets")

    bg = Palette("TILEMAP_PALETTE", art.TILEMAP_PALETTE)
    sp = Palette("SPRITE_PALETTE", art.SPRITE_PALETTE)

    packed_tiles = build_tileset(bg)
    grid = build_level({name: index for index, (name, _a, _b, _c, _d) in enumerate(packed_tiles)})

    tilemap_h, bytes_per_tile = emit_tilemap_header(packed_tiles)
    tilemap_cpp = emit_tilemap_source(packed_tiles, bytes_per_tile, grid)

    tilemap_palette_h = emit_palette_header(
        bg, "TilemapPalette.h", "TILEMAP_PALETTE_DATA", "TILEMAP_PALETTE_MAPPING",
        "/**\n"
        " * @file TilemapPalette.h\n"
        " * @brief The 16 RGB565 colors the sea and the islands render with.\n"
        " *\n"
        " * Installed with setBackgroundCustomPalette(). The engine stores the pointer\n"
        " * without copying, which is why this lives at namespace scope.\n"
        " *\n"
        " * Sampled against the NES palette: three blues for water depth, one cyan for\n"
        " * foam, and the same sand and rock browns any 8-bit island is built from.\n"
        " */")

    sprite_palette_h = emit_palette_header(
        sp, "SpritePalette.h", "SPRITE_PALETTE_DATA", "SPRITE_PALETTE_MAPPING",
        "/**\n"
        " * @file SpritePalette.h\n"
        " * @brief The 16 RGB565 colors every aircraft, tracer and explosion draws with.\n"
        " *\n"
        " * Installed with setSpriteCustomPalette(). Separate from the tilemap palette\n"
        " * because dual palette mode gives sprites their own 16 slots - so the sea and\n"
        " * the aircraft are not competing for the same table.\n"
        " *\n"
        " * Player and enemy share no color except black. On a screen holding a dozen\n"
        " * aircraft that is what keeps the two apart at a glance.\n"
        " */")

    player_h = emit_sprite_header(
        "PlayerSprites.h",
        "/**\n"
        " * @file PlayerSprites.h\n"
        " * @brief The player's P-38: level flight with a two-frame propeller, plus a\n"
        " *        banked frame each way.\n"
        " *\n"
        " * The twin-boom silhouette was picked over a single-engine fighter because at\n"
        " * 16x16 an aircraft has about a 12x14 usable footprint, and a shape with two\n"
        " * hard vertical lines through it stays legible against a moving sea. A single\n"
        " * fuselage at this size is a blob.\n"
        " *\n"
        " * Only the propeller hub pixels differ between the two level frames. A\n"
        " * propeller does not need to be drawn, it needs to flicker.\n"
        " */",
        [{"prefix": "PLAYER", "size": art.PLAYER_SPRITE_SIZE, "frames": art.PLAYER_FRAMES}],
        sp, "SpritePalette.h", "SPRITE_PALETTE_MAPPING")

    enemy_h = emit_sprite_header(
        "EnemySprites.h",
        "/**\n"
        " * @file EnemySprites.h\n"
        " * @brief Enemy aircraft, drawn nose-south - flying at the player, which is the\n"
        " *        only direction they ever travel.\n"
        " */",
        [{"prefix": "ENEMY", "size": art.ENEMY_SPRITE_SIZE, "frames": art.ENEMY_FRAMES}],
        sp, "SpritePalette.h", "SPRITE_PALETTE_MAPPING")

    effects_h = emit_sprite_header(
        "EffectSprites.h",
        "/**\n"
        " * @file EffectSprites.h\n"
        " * @brief Tracers and explosions.\n"
        " *\n"
        " * Projectiles are 8x8: a bullet is read by its color and its motion, never by\n"
        " * its shape, so spending 16x16 on one would cost four times the blit for\n"
        " * nothing. Player fire is a yellow vertical stroke, enemy fire a red disc -\n"
        " * shape and color both differ, so the distinction survives for a colorblind\n"
        " * player.\n"
        " */",
        [{"prefix": "BULLET", "size": art.PROJECTILE_SIZE, "frames": art.PROJECTILES},
         {"prefix": "EXPLOSION", "size": art.EXPLOSION_SIZE, "frames": art.EXPLOSION_FRAMES}],
        sp, "SpritePalette.h", "SPRITE_PALETTE_MAPPING")

    if args.preview:
        for name, _is_land, _doc, rows, _packed in packed_tiles:
            if name != "EMPTY":
                preview(rows, f"TILE_{name}")
        for name, _doc, rows in art.PLAYER_FRAMES + art.ENEMY_FRAMES:
            preview(rows, name)
        for name, _doc, rows in art.PROJECTILES + art.EXPLOSION_FRAMES:
            preview(rows, name)

    files = {
        "TilemapPalette.h": tilemap_palette_h,
        "SpritePalette.h": sprite_palette_h,
        "OceanTileMap.h": tilemap_h,
        "OceanTileMap.cpp": tilemap_cpp,
        "PlayerSprites.h": player_h,
        "EnemySprites.h": enemy_h,
        "EffectSprites.h": effects_h,
    }

    if args.check:
        print("art validated; round trip clean; nothing written")
    else:
        os.makedirs(out_dir, exist_ok=True)
        for filename, content in files.items():
            with open(os.path.join(out_dir, filename), "w", encoding="utf-8", newline="\n") as handle:
                handle.write(content)
            print(f"wrote {os.path.join(out_dir, filename)}  ({len(content):,} bytes)")

    tileset_bytes = len(packed_tiles) * bytes_per_tile
    level_bytes = LEVEL_WIDTH * LEVEL_HEIGHT
    sprite_count = (len(art.PLAYER_FRAMES) + len(art.ENEMY_FRAMES) + len(art.EXPLOSION_FRAMES))
    sprite_bytes = sprite_count * (art.PLAYER_SPRITE_SIZE ** 2 // 2)
    sprite_bytes += len(art.PROJECTILES) * (art.PROJECTILE_SIZE ** 2 // 2)

    print("")
    print(f"  tileset   {len(packed_tiles):3d} tiles   {tileset_bytes:6,d} B flash")
    print(f"  level     {LEVEL_WIDTH}x{LEVEL_HEIGHT}       {level_bytes:6,d} B flash")
    print(f"  sprites   {sprite_count + len(art.PROJECTILES):3d} frames  {sprite_bytes:6,d} B flash")
    print(f"  total                  {tileset_bytes + level_bytes + sprite_bytes:6,d} B flash, 0 B SRAM")


if __name__ == "__main__":
    main()
