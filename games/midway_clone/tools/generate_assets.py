# C++ emission
# --------------------------------------------------------------------------

def emit_byte_pool(packed, per_row, indent="        "):
    lines = []
    for offset in range(0, len(packed), per_row):
        chunk = packed[offset:offset + per_row]
        lines.append(indent + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    return lines


def emit_u16_rows(packed, width, height, indent="        "):
    """Sprite rows as uint16_t, which is how the existing examples declare them.

    Two packed bytes per uint16_t, low byte first: the array is reinterpret_cast
    to const uint8_t* at the point of use, so the literal has to match what a
    little-endian target reads back.
    """
    lines = []
    stride = width // 2
    for y in range(height):
        row = packed[y * stride:(y + 1) * stride]
        words = []
        for x in range(0, stride, 2):
            lo, hi = row[x], row[x + 1]
            words.append(f"0x{(lo | (hi << 8)):04X}")
        lines.append(indent + ", ".join(words) + ",")
    return lines


def emit_palette_header(palette, filename, struct_name, mapping_name, doc):
    guard = f"{GUARD_PREFIX}_{filename.upper().replace('.', '_')}"
    out = [BANNER, f"#ifndef {guard}", f"#define {guard}", "",
           '#include "graphics/Renderer.h"', "#include <stdint.h>", "",
           doc, "", f"namespace {NAMESPACE} {{", ""]

    out.append("    // --- RGB565 by engine Color slot ---")
    out.append("    // Indexed by Color, NOT by 4bpp pixel value. Slots the art never uses keep")
    out.append("    // their conventional color so Color::Red still renders red for text.")
    out.append(f"    static const uint16_t {struct_name}[16] = {{")
    used_slots = {slot for slot in palette.slot_of_value.values()}
    for index, slot in enumerate(COLOR_SLOTS):
        hex_str = palette.slot_hex[slot]
        rgb = hex_to_rgb565(hex_str)
        if slot in used_slots:
            symbol = next(s for v, s in
                          ((v, n[0]) for v, n in palette.notes.items())
                          if palette.slot_of_value[v] == slot)
            desc = next(n[2] for v, n in palette.notes.items()
                        if palette.slot_of_value[v] == slot)
            note = f"{slot}  '{symbol}'  {hex_str}  {desc}"
        else:
            note = f"{slot} - unused by art, conventional value kept"
        out.append(f"        0x{rgb:04X}, // {index:2d} {note}")
    out.append("    };")
    out.append("")

    out.append("    // --- 4bpp pixel value to engine Color slot ---")
    out.append("    // The blitter reads sprite.palette[pixelValue] as a Color and resolves that")
    out.append("    // slot against the table above. Entry 0 is never read: pixel value 0 is a")
    out.append("    // hole, so the first real color has to live at value 1.")
    out.append(f"    static const pixelroot32::graphics::Color {mapping_name}[16] = {{")
    for value in range(16):
        if value == 0:
            out.append("        pixelroot32::graphics::Color::Black, //  0 transparent - never read")
        elif value in palette.slot_of_value:
            slot = palette.slot_of_value[value]
            symbol = palette.notes[value][0]
            out.append(f"        pixelroot32::graphics::Color::{slot}, // {value:2d} '{symbol}' -> {slot}")
        else:
            out.append(f"        pixelroot32::graphics::Color::Black, // {value:2d} unused")
    out.append("    };")
    out.append("")
    out.append(f"}} // namespace {NAMESPACE}")
    out.append("")
    out.append(f"#endif // {guard}")
    out.append("")
    return "\n".join(out)


def wrap_doc(text, indent="     * "):
    return "\n".join(indent + line if line else indent.rstrip() for line in text.split("\n"))


