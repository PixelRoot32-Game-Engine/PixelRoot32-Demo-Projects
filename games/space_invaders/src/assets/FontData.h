/**
 * @file FontData.h
 * @brief The arcade 8x8 text font, transcribed from the reference character sheet.
 *
 * The sheet carries five rows of eight glyphs (A-H, I-P, Q-X, Y Z 0-5, 6-9 `<`
 * `>` `=` `*`) plus a last row with `?` and `-`. Everything here is copied from
 * those cells pixel for pixel, not from a system font, so the HUD reads like the
 * arcade's character generator instead of a generic pixel face.
 *
 * Storage follows the engine's 1bpp `Sprite` convention exactly like the actor
 * sprites (`AlienSprites.h`): one `uint16_t` per row, one bit per pixel, MSB-first,
 * so bit 7 is the leftmost pixel of the 8 px cell and the ASCII picture beside each
 * row reads left-to-right in the same direction `drawSprite` walks the bits.
 *
 * `Font` indexes `glyphs[code - firstChar]`, so the table must stay contiguous.
 * It spans `' '` (32) through `'Z'` (90); codes the sheet does not carry point at
 * the one shared blank glyph, which keeps the advance identical for every
 * character while still leaving a real (empty) 8x8 sprite in the slot.
 */

