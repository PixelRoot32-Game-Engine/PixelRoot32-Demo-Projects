tile_art = [t[3] for t in art.OVERWORLD_TILES] + [t[3] for t in art.DUNGEON_TILES]
palette = build_palette(tile_art)

sprite_palette = build_palette([s[2] for s in art.PLAYER_SPRITES])

emit_palette_header(
    OUT / "TilemapPalette.h", "CLONE_TILEMAP_PALETTE_H",
    "The 16 RGB565 colors both tilemaps render with.",
    "TILEMAP_PALETTE_DATA", "TILEMAP_PALETTE_MAPPING", palette,
    "Installed with setBackgroundCustomPalette(). The engine stores the pointer\n"
    "without copying, which is why this lives at namespace scope.\n"
    "\n"
    "Sampled to match the NES first-quest overworld: tan ground, the two greens\n"
    "of the bushes and forest, the navy drop shadow under every bush, and the two\n"
    "browns of the mountains.")

emit_palette_header(
    OUT / "PlayerPalette.h", "CLONE_PLAYER_PALETTE_H",
    "The RGB565 colors Link renders with.",
    "PLAYER_SPRITE_PALETTE_RGB565", "PLAYER_PALETTE_MAPPING", sprite_palette,
    "Installed with setSpriteCustomPalette(). Separate from the tilemap palette\n"
    "because dual palette mode gives sprites their own 16 slots - so the world\n"
    "and the hero are not competing for the same table.\n"
    "\n"
    "Three colors and a hole: exactly one NES sprite palette, which is the whole\n"
    "budget the 1986 cartridge had for its hero.")

emit_tilemap("Overworld", "overworld", art.OVERWORLD_TILES, art.OVERWORLD_MAP,
             art.OVERWORLD_MAP_LEGEND, "TilemapPalette.h", "TILEMAP_PALETTE_MAPPING",
             "Four adjacent overworld screens, 15x11 tiles each, laid out 2x2.")

emit_tilemap("Dungeon", "dungeon", art.DUNGEON_TILES, art.DUNGEON_MAP,
             art.DUNGEON_MAP_LEGEND, "TilemapPalette.h", "TILEMAP_PALETTE_MAPPING",
             "Four dungeon rooms on the same 2x2 grid the overworld uses.")

emit_sprites(sprite_palette, "PLAYER_PALETTE_MAPPING")

print(f"tilemap palette : {len(palette)} colors  {''.join(palette)}")
print(f"sprite palette  : {len(sprite_palette)} colors  {''.join(sprite_palette)}")
print(f"wrote 7 files to {OUT}")
