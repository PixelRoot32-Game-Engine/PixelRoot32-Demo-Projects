#!/usr/bin/env python3
"""Gate the SFX bank against the WAD's original samples.

WHAT THIS PROVES, AND WHAT IT DOES NOT

Every one of the 108 cues is rendered through the **real ApuCore** at the
board's 22050 Hz, using `src/doomc/SfxCueEvent.h` (the same translation
`DoomAudio.cpp` calls) and `src/doomc/SfxBank.cpp` (the table the firmware
compiles). A cue fitted from a `DS*` lump is compared with that lump; a cue
fitted from a donor (the 53 ids the shareware WAD has no lump for) is compared
with the donor's original, which is the cue it copied. The rendered sound is
analysed with the same 16-segment analysis `tools/sfx_design.py` applied to
the original, and five numbers are compared:

  duration   within 5 % or 25 ms (whichever is looser);
  envelope   Pearson correlation over the 16 normalised RMS segments >= 0.80;
  class      the rendered sample classifies into the original's class
             (metallic / noise / pulse / triangle; the rule lives in
             sfx_design.classify() and is mirrored in tools/sfx_render.cpp);
  centroid   within a factor of 2 of the original's envelope-weighted mean;
  pitch      where the original has a reliable pitch (>= 0.5 of the segments,
             mean correlation >= 0.85), within 1.5 semitones of the rendered
             mean.

So this gate proves the cue **is the sound it claims to be**. It does not prove
the cue is *pleasant*: that takes a listening pass, and it is about taste, not
identity.

PROVING THE GATE CAN FAIL, two ways:

  ``--perturb`` scales every cue's frequency by 1.5 before rendering. The
  rendered pitch/centroid drift outside their windows, so the run must fail.
  ``--stub`` renders a fixed 440 Hz square instead of the bank. Duration,
  class and envelope all miss, so the run must fail.
  Without these, a gate that only ever sees the bank proves the bank runs.

ACCEPTED DEVIATIONS

A cue whose original RMS contour a single ADSR cannot follow is not hidden and
not "fixed" by weakening the gate. An envelope failure is recorded as
``accepted-deviation`` with the measured number and a reason derived from the
contour's own shape when either (a) the contour is multi-lobe (four or more
direction changes) and the fit already misses it, or (b) the render is not worse
than its own model by more than 0.15 (and at least 0.75 where the model reached
0.80). A tonal cue also records a centroid deviation when the original's ZCR
centroid is more than 2x its fundamental: one APU oscillator at the fundamental
has ZCR/2 = pitch, so matching the centroid would break the pitch gate. Any
other failure -- duration, class, an unfittable centroid on a noise cue, or a
pitch outside 1.5 semitones -- fails the run.

The record ``tools/sfx_fit.txt`` is regenerated by a normal (non-perturb,
non-stub) run; ``--no-record`` leaves it alone. The committed file is the
measurement, not a prediction.

    python tools/sfx_check.py --wad tools/DOOM1.WAD
    python tools/sfx_check.py --wad tools/DOOM1.WAD --perturb   # must FAIL
    python tools/sfx_check.py --wad tools/DOOM1.WAD --stub      # must FAIL

Exit 0 the gate is green, 1 a checked id failed, 2 unusable input or build.
"""
from __future__ import annotations

import argparse
import math
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

import sfx_design  # noqa: E402


def _pearson(left: list[float], right: list[float]) -> float:
    mean_l = sum(left) / len(left)
    mean_r = sum(right) / len(right)
    cov = sum((a - mean_l) * (b - mean_r) for a, b in zip(left, right))
    var_l = sum((a - mean_l) ** 2 for a in left)
    var_r = sum((b - mean_r) ** 2 for b in right)
    if var_l <= 0.0 or var_r <= 0.0:
        return 0.0
    return cov / math.sqrt(var_l * var_r)


def _semitone_distance(a: float, b: float) -> float:
    if a <= 0.0 or b <= 0.0:
        return 999.0
    return abs(12.0 * math.log(b / a, 2.0))


def _lobes(envelope: list[float]) -> int:
    changes = 0
    previous = 0
    for index in range(1, len(envelope)):
        delta = envelope[index] - envelope[index - 1]
        sign = 0 if abs(delta) < 1e-6 else (1 if delta > 0 else -1)
        if sign and previous and sign != previous:
            changes += 1
        if sign:
            previous = sign
    return changes


def build(workdir: Path, cxx: str, apu: Path) -> Path:
    apu_include = apu / "include"
    apu_source = apu / "src" / "ApuCore.cpp"
    if not apu_source.exists():
        raise SystemExit(
            f"sfx_check: {apu_source} is missing; run `pio run -e native` once so "
            "PlatformIO installs PixelRoot32-APU")
    ext = ".exe" if sys.platform == "win32" else ""
    exe = workdir / f"sfx_render{ext}"
    # `S_sfx[]` is C and stays C; compile it with the same compiler in C mode
    # instead of re-implementing the name table in the harness.
    sounds_object = workdir / "sounds.o"
    sounds = subprocess.run(
        [cxx, "-x", "c", "-std=gnu99", "-O2", "-c",
         str(ROOT / "lib" / "doom" / "sounds.c"), "-o", str(sounds_object)],
        capture_output=True, text=True)
    if sounds.returncode != 0:
        raise RuntimeError("building sounds.c failed:\n" + (sounds.stderr or sounds.stdout))
    command = [
        cxx, "-std=c++17", "-O2", "-Wall", "-Wextra",
        "-I", str(apu_include),
        "-I", str(ROOT / "src"),
        "-I", str(ROOT / "lib" / "doom"),
        "-o", str(exe),
        str(ROOT / "tools" / "sfx_render.cpp"),
        str(ROOT / "src" / "doomc" / "SfxBank.cpp"),
        str(apu_source),
        str(sounds_object),
    ]
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError("building sfx_render failed:\n" + (result.stderr or result.stdout))
    return exe


LINE = re.compile(
    r"id=(?P<id>\d+) name=(?P<name>\S+) dur=(?P<dur>[\d.]+) "
    r"env=(?P<env>[\d.,]+) cen=(?P<cen>[\d.,]+) "
    r"pfr=(?P<pfr>[\d.]+) pconf=(?P<pconf>[\d.]+) "
    r"pmean=(?P<pmean>[\d.]+) class=(?P<cls>\w+)")


def parse(text: str) -> dict[int, dict]:
    measured = {}
    for line in text.splitlines():
        match = LINE.match(line.strip())
        if not match:
            continue
        measured[int(match["id"])] = {
            "name": match["name"],
            "duration": float(match["dur"]),
            "envelope": [float(value) for value in match["env"].split(",")],
            "centroid": [float(value) for value in match["cen"].split(",")],
            "pitch_fraction": float(match["pfr"]),
            "pitch_confidence": float(match["pconf"]),
            "pitch_mean": float(match["pmean"]),
            "class": match["cls"],
        }
    return measured


def reason_for(cue: dict, model_corr: float, measured_corr: float) -> str:
    envelope = cue["stats"]["envelope"]
    lobes = _lobes(envelope)
    spread = cue["stats"]["env_std"]
    if spread < 0.10:
        return (f"steady-state RMS (sigma={spread:.2f}, {lobes} lobes): a single "
                f"ADSR has no trend to correlate with (model r={model_corr:.3f}, "
                f"measured r={measured_corr:.3f})")
    return (f"multi-lobe RMS contour ({lobes} direction changes, sigma={spread:.2f}): "
            f"one ADSR cannot follow it (model r={model_corr:.3f}, "
            f"measured r={measured_corr:.3f})")


def evaluate(cues: list[dict], measured: dict[int, dict]) -> tuple[list[dict], dict[int, dict]]:
    findings: list[dict] = []
    record: dict[int, dict] = {}
    for sfx_id, cue in enumerate(cues):
        if sfx_id == 0:
            continue
        rendered = measured.get(sfx_id)
        if rendered is None:
            findings.append({"id": sfx_id, "name": cue["name"],
                             "metric": "render", "detail": "no rendered line"})
            continue
        statistics = cue["stats"]
        checks = {}
        duration_error = abs(rendered["duration"] - statistics["duration"])
        checks["duration"] = duration_error <= max(0.05 * statistics["duration"], 0.025)
        envelope_corr = _pearson(statistics["envelope"], rendered["envelope"])
        checks["envelope"] = envelope_corr >= 0.80
        checks["class"] = rendered["class"] == cue["class"]
        original_centroid = statistics["centroid_mean"]
        rendered_centroid = sum(c * w for c, w in zip(rendered["centroid"],
                                                      rendered["envelope"])) \
            / (sum(rendered["envelope"]) or 1.0)
        checks["centroid"] = (original_centroid / 2.0 <= rendered_centroid
                              <= original_centroid * 2.0)
        tonal = (statistics["pitch_fraction"] >= 0.5
                 and statistics["pitch_confidence"] >= 0.85)
        pitch_error = 0.0
        if tonal:
            pitch_error = _semitone_distance(statistics["pitch_mean"],
                                             rendered["pitch_mean"])
            checks["pitch"] = pitch_error <= 1.5
        else:
            checks["pitch"] = True

        failed = [name for name, ok in checks.items() if not ok]
        excused: list[str] = []
        if "envelope" in failed:
            model_corr = cue["adsr"]["corr"]
            lobes = _lobes(cue["stats"]["envelope"])
            # The fit itself, or the LFSR's own segment-to-segment RMS jitter,
            # is what missed. A multi-lobe contour (two bursts, a creak, a
            # speech envelope) is not representable by one ADSR at all; where
            # the contour is simpler, the render has to stay within 0.15 of its
            # own model, and at least 0.75 where the model did reach 0.80.
            if model_corr < 0.80:
                if lobes >= 4 or envelope_corr >= model_corr - 0.15:
                    excused.append("envelope")
            elif envelope_corr >= 0.75 and envelope_corr >= model_corr - 0.15:
                excused.append("envelope")
        if "centroid" in failed and cue["class"] in ("pulse", "triangle", "saw"):
            ratio = (statistics["centroid_mean"] / statistics["pitch_mean"]
                     if statistics["pitch_mean"] > 0 else 0.0)
            if ratio > 2.0 and checks["pitch"]:
                excused.append("centroid")
        accepted = bool(failed) and set(failed) <= set(excused)

        status = "pass"
        if failed and accepted:
            status = "accepted-deviation"
        elif failed:
            status = "fail"

        gate = {
            "duration": "ok" if checks["duration"] else f"off {duration_error:.4f}s",
            "env_corr": f"{envelope_corr:.3f}",
            "class": "ok" if checks["class"] else f"{rendered['class']} != {cue['class']}",
            "centroid": "ok" if checks["centroid"]
            else f"{rendered_centroid:.0f} vs {original_centroid:.0f}",
            "pitch": "ok" if checks["pitch"] else f"{pitch_error:.2f} st",
            "status": status,
        }
        if status == "accepted-deviation":
            reasons = []
            if "envelope" in failed:
                reasons.append(reason_for(cue, cue["adsr"]["corr"], envelope_corr))
            if "centroid" in failed:
                ratio = statistics["centroid_mean"] / statistics["pitch_mean"]
                reasons.append(
                    f"the original's ZCR centroid is {ratio:.1f}x its fundamental "
                    f"(broadband 8-bit grit); one APU oscillator at the fundamental "
                    f"has ZCR/2 = pitch, so matching the centroid would break the "
                    f"pitch gate")
            gate["reason"] = "; ".join(reasons)
        record[sfx_id] = gate
        if status == "fail":
            findings.append({"id": sfx_id, "name": cue["name"],
                             "metric": ",".join(failed),
                             "detail": f"env {envelope_corr:.3f} "
                                       f"class {rendered['class']}/{cue['class']} "
                                       f"centroid {rendered_centroid:.0f}/{original_centroid:.0f} "
                                       f"pitch {pitch_error:.2f} st"})
    return findings, record


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="SFX bank gate")
    parser.add_argument("--wad", type=Path, default=ROOT / "tools" / "DOOM1.WAD")
    parser.add_argument("--apu", type=Path,
                        default=ROOT / ".pio" / "libdeps" / "native" / "PixelRoot32-APU")
    parser.add_argument("--cxx", default="g++")
    parser.add_argument("--perturb", action="store_true")
    parser.add_argument("--stub", action="store_true")
    parser.add_argument("--no-record", action="store_true")
    args = parser.parse_args(argv)

    text = (ROOT / "lib" / "doom" / "sounds.c").read_text(encoding="utf-8", errors="replace")
    match = re.search(r"const sfxinfo_t S_sfx\[\]\s*=\s*\{(.*?)\n\};", text, re.S)
    words = re.findall(r'\{"([^"]+)"', match.group(1))
    lumps = sfx_design.read_wad(args.wad)
    cues, _ = sfx_design.derive(words, lumps)

    with tempfile.TemporaryDirectory(prefix="sfx_check_") as temporary:
        workdir = Path(temporary)
        try:
            exe = build(workdir, args.cxx, args.apu)
        except (RuntimeError, OSError) as error:
            print(f"FAIL build: {error}")
            return 2
        command = [str(exe)]
        if args.perturb:
            command.append("--perturb")
        if args.stub:
            command.append("--stub")
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode != 0:
            print("FAIL render: " + (result.stderr or result.stdout))
            return 2
        measured = parse(result.stdout)
        if len(measured) != 108:
            print(f"FAIL render: {len(measured)} lines for 108 cues")
            return 2

    findings, record = evaluate(cues, measured)

    if args.perturb or args.stub:
        label = "--perturb" if args.perturb else "--stub"
        if not findings:
            print(f"FAIL {label}: every checked id passed; the gate cannot see the difference")
            return 1
        print(f"OK {label}: the gate failed as it must ({len(findings)} checked ids)")
        return 0

    if not args.no_record:
        report = sfx_design.render_report(cues, record)
        (ROOT / "tools" / "sfx_fit.txt").write_text(report, encoding="utf-8", newline="\n")

    checked = len(cues) - 1
    accepted = sum(1 for gate in record.values() if gate.get("status") == "accepted-deviation")
    correlations = [
        _pearson(cue["stats"]["envelope"], measured[index]["envelope"])
        for index, cue in enumerate(cues) if index]
    for finding in findings:
        print(f"FAIL id={finding['id']} {finding['name']}: "
              f"{finding['metric']} ({finding['detail']})")
    if findings:
        print(f"FAIL sfx_check: {len(findings)} of {checked} checked ids failed")
        return 1
    worst = min(correlations) if correlations else 1.0
    mean = sum(correlations) / len(correlations) if correlations else 1.0
    print(f"OK sfx_check: {checked} measured, {checked - accepted} pass, "
          f"{accepted} accepted-deviation, 0 failed")
    print(f"   envelope r: worst {worst:.3f}, mean {mean:.3f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
