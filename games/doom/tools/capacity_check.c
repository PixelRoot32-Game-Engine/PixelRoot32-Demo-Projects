static uint8_t* readFile(const char* path, size_t* size) {
    FILE* handle = fopen(path, "rb");
    uint8_t* data;
    long length;

    if (handle == NULL) {
        return NULL;
    }
    if (fseek(handle, 0, SEEK_END) != 0) {
        fclose(handle);
        return NULL;
    }
    length = ftell(handle);
    if (length < 0) {
        fclose(handle);
        return NULL;
    }
    if (fseek(handle, 0, SEEK_SET) != 0) {
        fclose(handle);
        return NULL;
    }
    data = (uint8_t*)malloc((size_t)length);
    if (data == NULL) {
        fclose(handle);
        return NULL;
    }
    if (fread(data, 1, (size_t)length, handle) != (size_t)length) {
        free(data);
        fclose(handle);
        return NULL;
    }
    fclose(handle);
    *size = (size_t)length;
    return data;
}

static int parseCapacities(const char* text, capacity_set_t* out) {
    unsigned drawsegs;
    unsigned planes;
    unsigned clipRanges;
    unsigned clipBlocks;
    unsigned visSprites;
    unsigned openings;

    if (sscanf(text, "%u,%u,%u,%u,%u,%u", &drawsegs, &planes, &clipRanges,
               &clipBlocks, &visSprites, &openings) != 6) {
        return 0;
    }
    out->drawsegs = (uint16_t)drawsegs;
    out->planes = (uint16_t)planes;
    out->clipRanges = (uint16_t)clipRanges;
    out->clipBlocks = (uint16_t)clipBlocks;
    out->visSprites = (uint16_t)visSprites;
    out->openingBlocks = (uint16_t)openings;
    return 1;
}

int main(int argc, char** argv) {
    const char* wadPath = NULL;
    const char* mapName = "E1M1";
    const char* scope = "whole";
    const char* scriptPath = NULL;
    const char* capacitiesText = NULL;
    capacity_set_t board;
    capacity_set_t ample;
    wad_state_t wad;
    doom_map_source_t source;
    doom_map_t map;
    r_view_storage_t storage;
    r_view_state_t view;
    r_draw_surface_t surface;
    r_light_t light;
    texture_cache_t cache;
    flat_cache_t flatCache;
    r_tex_source_t texSource;
    sprite_cache_t spriteCache;
    r_sprite_source_t spriteSource;
    viewpoint_t* list = NULL;
    int listCount = 0;
    int* indices;
    int indexCount;
    uint8_t* bytes;
    size_t size = 0;
    int marker;
    int index;
    int colormapLump;
    int texture1Lump;
    int pnamesLump;
    sweep_result_t result;

    for (index = 1; index < argc; ++index) {
        if (strcmp(argv[index], "--map") == 0 && index + 1 < argc) {
            mapName = argv[++index];
        } else if (strcmp(argv[index], "--scope") == 0 && index + 1 < argc) {
            scope = argv[++index];
        } else if (strcmp(argv[index], "--script") == 0 && index + 1 < argc) {
            scriptPath = argv[++index];
        } else if (strcmp(argv[index], "--capacities") == 0 && index + 1 < argc) {
            capacitiesText = argv[++index];
        } else if (wadPath == NULL) {
            wadPath = argv[index];
        } else {
            fprintf(stderr, "capacity_check: unknown argument %s\n", argv[index]);
            return 2;
        }
    }
    if (wadPath == NULL) {
        fprintf(stderr, "usage: capacity_check <path-to-WAD> [--map NAME] "
                        "[--scope whole|walkable] [--script FILE] "
                        "[--capacities D,P,R,B,V,O]\n");
        return 2;
    }
    ample.drawsegs = AMPLE_DRAWSEGS;
    ample.planes = AMPLE_PLANES;
    ample.clipRanges = R_MAX_CLIP_SEGS;
    ample.clipBlocks = AMPLE_CLIP_BLOCKS;
    ample.visSprites = AMPLE_VISSPRITES;
    ample.openingBlocks = AMPLE_OPENING_BLOCKS;
    board = ample;
    if (capacitiesText != NULL && !parseCapacities(capacitiesText, &board)) {
        fprintf(stderr, "capacity_check: --capacities wants six comma-separated "
                        "unsigned values\n");
        return 2;
    }

    bytes = readFile(wadPath, &size);
    if (bytes == NULL) {
        fprintf(stderr, "capacity_check: cannot read %s\n", wadPath);
        return 2;
    }
    if (wad_open(&wad, bytes, size) != WAD_ERR_OK) {
        fprintf(stderr, "capacity_check: not a WAD\n");
        free(bytes);
        return 2;
    }
    marker = W_CheckNumForName(&wad, mapName);
    colormapLump = W_CheckNumForName(&wad, "COLORMAP");
    texture1Lump = W_CheckNumForName(&wad, "TEXTURE1");
    pnamesLump = W_CheckNumForName(&wad, "PNAMES");
    if (marker < 0 || marker + 1 + DOOM_MAP_LUMP_COUNT > wad.numLumps
        || colormapLump < 0 || texture1Lump < 0 || pnamesLump < 0) {
        fprintf(stderr, "capacity_check: %s, COLORMAP, TEXTURE1 or PNAMES is missing\n",
                mapName);
        free(bytes);
        return 2;
    }

    memset(&cache, 0, sizeof cache);
    cache.wad = &wad;
    cache.texture1 = W_LumpPointer(&wad, texture1Lump);
    cache.texture1Size = (size_t)W_LumpLength(&wad, texture1Lump);
    index = W_CheckNumForName(&wad, "TEXTURE2");
    if (index >= 0) {
        cache.texture2 = W_LumpPointer(&wad, index);
        cache.texture2Size = (size_t)W_LumpLength(&wad, index);
    }
    cache.pnames = W_LumpPointer(&wad, pnamesLump);
    cache.pnamesSize = (size_t)W_LumpLength(&wad, pnamesLump);

    if (r_light_init(&light, W_LumpPointer(&wad, colormapLump),
                     (size_t)W_LumpLength(&wad, colormapLump)) != R_LIGHT_OK) {
        fprintf(stderr, "capacity_check: the COLORMAP lump is not 34 x 256 B\n");
        free(bytes);
        return 2;
    }

    for (index = 0; index < DOOM_MAP_LUMP_COUNT; ++index) {
        const int lump = marker + 1 + index;

        source.data[index] = W_LumpPointer(&wad, lump);
        source.size[index] = (size_t)W_LumpLength(&wad, lump);
    }
    if (doom_map_open(&map, &source) != DOOM_MAP_OK) {
        fprintf(stderr, "capacity_check: %s rejected with doom_map error %d\n",
                mapName, (int)map.error);
        free(bytes);
        return 2;
    }

    memset(&storage, 0, sizeof storage);
    storage.drawsegs = g_drawsegs;
    storage.drawsegCapacity = AMPLE_DRAWSEGS;
    storage.planes.planes = g_planes;
    storage.planes.capacity = AMPLE_PLANES;
    storage.planes.count = 0;
    storage.clipRanges = g_clips;
    storage.clipRangeCapacity = R_MAX_CLIP_SEGS;
    storage.floorClip = g_floorClip;
    storage.ceilingClip = g_ceilingClip;
    storage.visSprites = g_visSprites;
    storage.visSpriteCapacity = AMPLE_VISSPRITES;
    storage.clipBlocks = g_clipBlocks;
    storage.clipBlockCapacity = AMPLE_CLIP_BLOCKS;
    storage.openingBlocks = g_openingBlocks;
    storage.openingBlockCapacity = AMPLE_OPENING_BLOCKS;
    if (r_bsp_init(&view, &map, &storage) != R_BSP_OK) {
        fprintf(stderr, "capacity_check: view rejected\n");
        free(bytes);
        return 2;
    }

    memset(&texSource, 0, sizeof texSource);
    texSource.resolve = resolveTexture;
    texSource.context = &cache;
    memset(&flatCache, 0, sizeof flatCache);
    flatCache.wad = &wad;
    texSource.resolveFlat = resolveFlat;
    texSource.flatContext = &flatCache;
    texSource.skyTexture = r_pack_name(kSkyTextureName);
    memset(&spriteCache, 0, sizeof spriteCache);
    spriteCache.wad = &wad;
    spriteSource.resolve = resolveSprite;
    spriteSource.context = &spriteCache;
    surface.pixels = g_pixels;
    surface.width = R_SCREEN_WIDTH;
    surface.height = R_VIEW_HEIGHT;
    surface.covered = g_covered;
    surface.planeMask = g_planeMask;
    surface.spriteMask = g_spriteMask;
    surface.tierPixels[R_DRAW_TIER_MID] = 0u;
    surface.tierPixels[R_DRAW_TIER_TOP] = 0u;
    surface.tierPixels[R_DRAW_TIER_BOTTOM] = 0u;
    surface.planePixels = 0u;
    surface.planeSpans = 0u;
    surface.spritePixels = 0u;

    if (scriptPath != NULL) {
        if (!readViewpointFile(scriptPath, &list, &listCount) || listCount == 0) {
            fprintf(stderr, "capacity_check: cannot read the viewpoint file %s\n",
                    scriptPath);
            free(bytes);
            return 2;
        }
        scope = "script";
    } else if (!buildSweepViewpoints(&map, &list, &listCount)) {
        fprintf(stderr, "capacity_check: cannot build the viewpoint list\n");
        free(bytes);
        return 2;
    }

    /* The index list the scope selects: every viewpoint, or only the walkable
     * ones. Built once so both runs visit exactly the same points. */
    indices = (int*)malloc(sizeof(int) * (size_t)listCount);
    if (indices == NULL) {
        fprintf(stderr, "capacity_check: out of memory\n");
        free(list);
        free(bytes);
        return 2;
    }
    indexCount = 0;
    for (index = 0; index < listCount; ++index) {
        if (scriptPath != NULL || strcmp(scope, "walkable") != 0
            || isWalkable(&map, &list[index])) {
            indices[indexCount++] = index;
        }
    }

    printf("WAD %s %s\n", mapName, scope);
    runSweep(&view, &surface, &texSource, &light, &spriteSource, list, indices,
             indexCount, &ample, &result);
    printCapLine(mapName, scope, list, indexCount, &result);

    runSweep(&view, &surface, &texSource, &light, &spriteSource, list, indices,
             indexCount, &board, &result);
    printRefusals(mapName, scope, list, &result);
    if (scriptPath != NULL) {
        int refused = 0;

        for (index = 0; index < result.refusalCount; ++index) {
            refused += result.refusals[index].count;
        }
        printf("CAP-SCRIPT %s tics=%d refusals=%d\n", mapName, indexCount, refused);
    }

    free(indices);
    free(list);
    freeTextures(&cache);
    free(bytes);
    return 0;
}
