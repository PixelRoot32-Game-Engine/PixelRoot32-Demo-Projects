/**
 * @brief Renders one viewpoint through the four passes and reports its cost.
 *
 * The pass order and the surface clearing are rsegs_check.c's, so a peak this
 * harness reports is the peak that harness would consume for the same view.
 *
 * @param driver  The initialised view state.
 * @param surface The surface the passes write into.
 * @param caches  The resolution policies (textures, flats, sprites).
 * @param view    The viewpoint to render.
 * @param out     Receives the counts this view consumed.
 * @param stage   Receives the refusing stage, when the view is refused.
 * @param code    Receives the refusing pass's error code.
 * @return 1 when every pass accepted the view, 0 when one refused.
 */
static int renderViewpoint(r_view_state_t* driver, r_draw_surface_t* surface,
                           r_tex_source_t* textures, r_light_t* light,
                           r_sprite_source_t* spriteSource, const viewpoint_t* view,
                           const capacity_set_t* capacities, uint32_t out[METRIC_COUNT],
                           const char** stage, int* code) {
    r_view_params_t params;
    r_segs_error_t walls;
    r_plane_error_t planes;
    r_things_error_t masked;
    r_masked_stats_t stats;
    int spriteCount;

    params.x = view->x;
    params.y = view->y;
    params.z = view->z;
    params.angle = view->angle;
    params.extralight = 0;
    params.skyPicNum = r_pack_name(kSkyFlatName);

    /* Reset the caller-owned sizes for this run, so neither the ample nor the
     * board pass inherits the other's capacity. The arrays are shared because
     * only one run is live at a time. */
    driver->storage.drawsegCapacity = capacities->drawsegs;
    driver->storage.planes.capacity = capacities->planes;
    driver->storage.clipRangeCapacity = capacities->clipRanges;
    driver->storage.clipBlockCapacity = capacities->clipBlocks;
    driver->storage.visSpriteCapacity = capacities->visSprites;
    driver->storage.openingBlockCapacity = capacities->openingBlocks;

    memset(g_pixels, 0xFF, sizeof g_pixels);
    memset(g_covered, 0, sizeof g_covered);
    memset(g_planeMask, 0, sizeof g_planeMask);
    memset(g_spriteMask, 0, sizeof g_spriteMask);
    memset(out, 0, sizeof(uint32_t) * METRIC_COUNT);
    surface->tierPixels[R_DRAW_TIER_MID] = 0u;
    surface->tierPixels[R_DRAW_TIER_TOP] = 0u;
    surface->tierPixels[R_DRAW_TIER_BOTTOM] = 0u;
    surface->planePixels = 0u;
    surface->planeSpans = 0u;
    surface->spritePixels = 0u;

    *stage = "walk";
    if (r_bsp_render(driver, &params) != R_BSP_OK) {
        *code = (int)driver->error;
        return 0;
    }
    out[METRIC_DRAWSEGS] = driver->drawsegCount;
    out[METRIC_PLANES] = driver->storage.planes.count;
    out[METRIC_CLIP_RANGES] = driver->clipRangeCount;

    *stage = "walls";
    walls = r_wall_emit(driver, surface, textures, light);
    if (walls != R_SEGS_OK) {
        *code = (int)walls;
        return 0;
    }
    out[METRIC_CLIP_BLOCKS] = driver->clipBlocksUsed;
    out[METRIC_OPENINGS] = driver->openingBlocksUsed;

    *stage = "planes";
    planes = r_plane_draw(driver, surface, textures, light);
    if (planes != R_PLANE_OK) {
        *code = (int)planes;
        return 0;
    }

    *stage = "sprites";
    spriteCount = buildSprites(driver->map, &params, g_sprites, HARNESS_SPRITES);
    if (spriteCount < 0) {
        *code = -1;
        return 0;
    }

    *stage = "masked";
    masked = r_masked_emit(driver, surface, textures, light, g_sprites,
                           (uint16_t)spriteCount, spriteSource, &stats);
    if (masked != R_THINGS_OK) {
        *code = (int)masked;
        return 0;
    }
    out[METRIC_VISSPRITES] = stats.drawn;
    return 1;
}

/* --- Viewpoint list ------------------------------------------------------ */

static int buildSweepViewpoints(const doom_map_t* map, viewpoint_t** list, int* count) {
    const uint32_t subsectorCount = map->lumps[DOOM_MAP_SSECTORS].count;
    const uint32_t sectorCount = map->lumps[DOOM_MAP_SECTORS].count;
    const uint32_t segCount = map->lumps[DOOM_MAP_SEGS].count;
    fixed_t* boxMinX;
    fixed_t* boxMinY;
    fixed_t* boxMaxX;
    fixed_t* boxMaxY;
    uint8_t* boxSet;
    viewpoint_t* frames;
    uint32_t index;
    int capacity;
    int total = 0;

    capacity = (int)((subsectorCount + sectorCount) * ANGLE_COUNT);
    frames = (viewpoint_t*)malloc(sizeof(viewpoint_t) * (size_t)capacity);
    boxMinX = (fixed_t*)malloc(sizeof(fixed_t) * (size_t)sectorCount);
    boxMinY = (fixed_t*)malloc(sizeof(fixed_t) * (size_t)sectorCount);
    boxMaxX = (fixed_t*)malloc(sizeof(fixed_t) * (size_t)sectorCount);
    boxMaxY = (fixed_t*)malloc(sizeof(fixed_t) * (size_t)sectorCount);
    boxSet = (uint8_t*)calloc((size_t)sectorCount, 1u);
    if (frames == NULL || boxMinX == NULL || boxMinY == NULL || boxMaxX == NULL
        || boxMaxY == NULL || boxSet == NULL) {
        free(frames);
        free(boxMinX);
        free(boxMinY);
        free(boxMaxX);
        free(boxMaxY);
        free(boxSet);
        return 0;
    }

    for (index = 0; index < segCount; ++index) {
        doom_seg_t seg;
        doom_vertex_t v1;
        doom_vertex_t v2;
        uint16_t front = 0;
        uint16_t back = 0;
        uint16_t sectors[2];
        int hasBack;
        int side;
        int sideCount;

        doom_map_get_seg(map, (uint16_t)index, &seg);
        doom_map_get_vertex(map, seg.v1, &v1);
        doom_map_get_vertex(map, seg.v2, &v2);
        hasBack = doom_map_seg_sectors(map, &seg, &front, &back);
        sectors[0] = front;
        sectors[1] = back;
        sideCount = hasBack ? 2 : 1;
        for (side = 0; side < sideCount; ++side) {
            const uint16_t sector = sectors[side];

            if (!boxSet[sector]) {
                boxSet[sector] = 1u;
                boxMinX[sector] = v1.x < v2.x ? v1.x : v2.x;
                boxMaxX[sector] = v1.x < v2.x ? v2.x : v1.x;
                boxMinY[sector] = v1.y < v2.y ? v1.y : v2.y;
                boxMaxY[sector] = v1.y < v2.y ? v2.y : v1.y;
            } else {
                if (v1.x < boxMinX[sector]) {
                    boxMinX[sector] = v1.x;
                }
                if (v2.x < boxMinX[sector]) {
                    boxMinX[sector] = v2.x;
                }
                if (v1.x > boxMaxX[sector]) {
                    boxMaxX[sector] = v1.x;
                }
                if (v2.x > boxMaxX[sector]) {
                    boxMaxX[sector] = v2.x;
                }
                if (v1.y < boxMinY[sector]) {
                    boxMinY[sector] = v1.y;
                }
                if (v2.y < boxMinY[sector]) {
                    boxMinY[sector] = v2.y;
                }
                if (v1.y > boxMaxY[sector]) {
                    boxMaxY[sector] = v1.y;
                }
                if (v2.y > boxMaxY[sector]) {
                    boxMaxY[sector] = v2.y;
                }
            }
        }
    }

    for (index = 0; index < subsectorCount; ++index) {
        doom_subsector_t sub;
        doom_seg_t seg;
        doom_vertex_t v1;
        doom_vertex_t v2;
        int k;

        doom_map_get_subsector(map, (uint16_t)index, &sub);
        doom_map_get_seg(map, sub.firstSeg, &seg);
        doom_map_get_vertex(map, seg.v1, &v1);
        doom_map_get_vertex(map, seg.v2, &v2);
        for (k = 0; k < ANGLE_COUNT; ++k) {
            viewpoint_t* entry = &frames[total++];

            /* Average in signed 64-bit: the operands are 16.16 and their sum can
             * cross the int32 range, so an unsigned average would fold a
             * negative coordinate to a large positive one. */
            entry->x = (fixed_t)(((int64_t)v1.x + (int64_t)v2.x) / 2);
            entry->y = (fixed_t)(((int64_t)v1.y + (int64_t)v2.y) / 2);
            entry->angle = (angle_t)(((uint64_t)k << 32) / ANGLE_COUNT);
            entry->z = 0;
            snprintf(entry->label, sizeof entry->label, "ss%u/a%d",
                     (unsigned)index, k);
        }
    }

    for (index = 0; index < sectorCount; ++index) {
        int k;

        if (!boxSet[index]) {
            continue;
        }
        for (k = 0; k < ANGLE_COUNT; ++k) {
            viewpoint_t* entry = &frames[total++];

            entry->x = (fixed_t)(((int64_t)boxMinX[index] + (int64_t)boxMaxX[index]) / 2);
            entry->y = (fixed_t)(((int64_t)boxMinY[index] + (int64_t)boxMaxY[index]) / 2);
            entry->angle = (angle_t)(((uint64_t)k << 32) / ANGLE_COUNT);
            entry->z = 0;
            snprintf(entry->label, sizeof entry->label, "sec%u/a%d",
                     (unsigned)index, k);
        }
    }

    for (index = 0; index < (uint32_t)total; ++index) {
        uint16_t sectorIndex;

        if (!sectorAt(map, frames[index].x, frames[index].y, &sectorIndex)) {
            frames[index].z = R_VIEWHEIGHT;
            continue;
        }
        {
            doom_sector_t sector;

            doom_map_get_sector(map, sectorIndex, &sector);
            frames[index].z = sector.floorHeight + R_VIEWHEIGHT;
        }
    }

    free(boxMinX);
    free(boxMinY);
    free(boxMaxX);
    free(boxMaxY);
    free(boxSet);
    *list = frames;
    *count = total;
    return 1;
}

/* True when the point stands in a sector the player fits in, by the rule this
 * harness's header states: a floor-to-ceiling gap of at least 56 map units. */
static int isWalkable(const doom_map_t* map, const viewpoint_t* view) {
    uint16_t sectorIndex;
    doom_sector_t sector;

    if (!sectorAt(map, view->x, view->y, &sectorIndex)) {
        return 0;
    }
    doom_map_get_sector(map, sectorIndex, &sector);
    return (sector.ceilingHeight - sector.floorHeight) >= WALKABLE_HEIGHT;
}

static int readViewpointFile(const char* path, viewpoint_t** list, int* count) {
    FILE* handle = fopen(path, "r");
    viewpoint_t* frames = NULL;
    int capacity = 0;
    int total = 0;
    double x;
    double y;
    double z;
    double angle;

    if (handle == NULL) {
        return 0;
    }
    while (fscanf(handle, "%lf %lf %lf %lf", &x, &y, &z, &angle) == 4) {
        if (total >= capacity) {
            viewpoint_t* grown;

            capacity = capacity == 0 ? 256 : capacity * 2;
            grown = (viewpoint_t*)realloc(frames, sizeof(viewpoint_t) * (size_t)capacity);
            if (grown == NULL) {
                fclose(handle);
                free(frames);
                return 0;
            }
            frames = grown;
        }
        frames[total].x = (fixed_t)(int32_t)x;
        frames[total].y = (fixed_t)(int32_t)y;
        frames[total].z = (fixed_t)(int32_t)z;
        frames[total].angle = (angle_t)(uint32_t)(int64_t)angle;
        snprintf(frames[total].label, sizeof frames[total].label, "tic%d", total);
        ++total;
    }
    fclose(handle);
    *list = frames;
    *count = total;
    return 1;
}

/* --- Reporting ----------------------------------------------------------- */

static void notePeak(metric_peak_t* peaks, int metric, uint32_t value, int at) {
    if (value > peaks[metric].value) {
        peaks[metric].value = value;
        peaks[metric].at = at;
    }
}

static refusal_entry_t* noteRefusal(sweep_result_t* result, const char* stage, int code,
                                    int at) {
    int index;

    for (index = 0; index < result->refusalCount; ++index) {
        if (result->refusals[index].code == code
            && strcmp(result->refusals[index].stage, stage) == 0) {
            ++result->refusals[index].count;
            return &result->refusals[index];
        }
    }
    if (result->refusalCount >= MAX_REFUSALS) {
        return NULL;
    }
    {
        refusal_entry_t* entry = &result->refusals[result->refusalCount++];

        entry->stage = stage;
        entry->code = code;
        entry->count = 1;
        entry->first = at;
        return entry;
    }
}

static void runSweep(r_view_state_t* driver, r_draw_surface_t* surface,
                     r_tex_source_t* textures, r_light_t* light,
                     r_sprite_source_t* spriteSource, const viewpoint_t* list,
                     const int* indices, int indexCount, const capacity_set_t* capacities,
                     sweep_result_t* result) {
    int position;

    memset(result, 0, sizeof *result);
    for (position = 0; position < indexCount; ++position) {
        uint32_t used[METRIC_COUNT];
        const char* stage = "walk";
        int code = 0;
        int metric;
        int accepted;

        accepted = renderViewpoint(driver, surface, textures, light, spriteSource,
                                   &list[indices[position]], capacities, used, &stage,
                                   &code);
        /* The walk's overflow flag belongs to this viewpoint whether or not a
         * later pass also refused it: a caller that reads only the success path
         * would hide dropped geometry behind a clip-pool refusal. */
        if (driver->drawsegOverflowed != 0u) {
            ++result->drawsegOverflow;
        }
        if (accepted) {
            for (metric = 0; metric < METRIC_COUNT; ++metric) {
                notePeak(result->peaks, metric, used[metric], indices[position]);
            }
        } else {
            (void)noteRefusal(result, stage, code, indices[position]);
        }
    }
}

static void printCapLine(const char* map, const char* scope, const viewpoint_t* list,
                         int viewpoints, const sweep_result_t* result) {
    int metric;

    printf("CAP %s scope=%s viewpoints=%d", map, scope, viewpoints);
    for (metric = 0; metric < METRIC_COUNT; ++metric) {
        printf(" %s=%u", kMetricNames[metric], result->peaks[metric].value);
        if (result->peaks[metric].value > 0u) {
            const viewpoint_t* vp = &list[result->peaks[metric].at];

            printf("@%s(%ld,%ld)", vp->label, (long)(vp->x >> FRACBITS),
                   (long)(vp->y >> FRACBITS));
        } else {
            printf("@-");
        }
    }
    printf("\n");
}

static void printRefusals(const char* map, const char* scope, const viewpoint_t* list,
                          const sweep_result_t* result) {
    int index;

    for (index = 0; index < result->refusalCount; ++index) {
        const refusal_entry_t* entry = &result->refusals[index];
        const viewpoint_t* vp = &list[entry->first];
        int tic = -1;

        if (strncmp(vp->label, "tic", 3) == 0) {
            tic = atoi(vp->label + 3);
        }
        printf("CAP-REFUSE %s scope=%s stage=%s code=%d viewpoints=%d first=%s(%ld,%ld) "
               "firsttic=%d\n",
               map, scope, entry->stage, entry->code, entry->count, vp->label,
               (long)(vp->x >> FRACBITS), (long)(vp->y >> FRACBITS), tic);
    }
    if (result->drawsegOverflow > 0) {
        printf("CAP-OVERFLOW %s scope=%s drawsegs=%d\n", map, scope,
               result->drawsegOverflow);
    }
}

